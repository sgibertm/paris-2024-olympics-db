    AW.IS_MEDALLIST = 'True'
GROUP BY
    P.FIRST_NAME,
    P.SECOND_NAME,
    A.ATHLETE_CODE
HAVING
    TOTAL_EVENTS > 10
ORDER BY
    TOTAL_EVENTS DESC;

